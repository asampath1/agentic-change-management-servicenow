"""Plain data models shared by the connectors, the agents and the orchestrator.

The models are deliberately source-agnostic: the same ``Incident`` comes out of the
local synthetic CSVs and out of the ServiceNow Table API, so every agent works the
same way offline and against a live PDI.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, field
from datetime import datetime
from typing import Any, Optional

TS_FMT = "%Y-%m-%d %H:%M:%S"


def parse_ts(value: str | None) -> Optional[datetime]:
    if not value:
        return None
    try:
        return datetime.strptime(value[:19], TS_FMT)
    except ValueError:
        return None


def priority_from(impact: int, urgency: int) -> int:
    """ServiceNow's default priority lookup (impact x urgency, 1..3 each)."""
    return {2: 1, 3: 2, 4: 3, 5: 4, 6: 5}.get(impact + urgency, 4)


@dataclass
class Incident:
    key: str                    # stable id: local "_key" (inc:0297) or ServiceNow number
    short_description: str
    description: str = ""
    number: Optional[str] = None
    sys_id: Optional[str] = None
    caller: Optional[str] = None
    category: Optional[str] = None
    impact: int = 3
    urgency: int = 3
    ci: Optional[str] = None
    business_service: Optional[str] = None
    opened_at: Optional[str] = None
    contact_type: Optional[str] = None
    state: Optional[str] = None
    # Only populated for HISTORICAL (resolved) incidents. Open incidents are redacted.
    assignment_group: Optional[str] = None
    work_notes: str = ""
    close_notes: str = ""
    caused_by: Optional[str] = None
    problem_id: Optional[str] = None
    resolved_at: Optional[str] = None

    @property
    def text(self) -> str:
        return f"{self.short_description}\n{self.description}"

    @property
    def is_monitoring_alert(self) -> bool:
        return self.short_description.startswith("[") or "Auto-generated by Azure Monitor" in self.description


@dataclass
class KBArticle:
    key: str
    title: str
    text: str
    symptoms: str = ""
    cause: str = ""
    resolver_group: Optional[str] = None
    runbook: Optional[str] = None
    safe_to_automate: bool = False
    meta: str = ""


@dataclass
class Change:
    key: str
    short_description: str
    description: str = ""
    ci: Optional[str] = None
    type: Optional[str] = None
    assignment_group: Optional[str] = None
    start: Optional[str] = None
    end: Optional[str] = None
    state: Optional[str] = None
    number: Optional[str] = None


@dataclass
class Problem:
    key: str
    short_description: str
    ci: Optional[str] = None
    known_error: bool = False
    cause_notes: str = ""
    workaround: str = ""
    number: Optional[str] = None


@dataclass
class ConfigItem:
    name: str
    description: str = ""
    support_group: Optional[str] = None
    os: str = ""
    ci_class: str = ""          # e.g. cmdb_ci_win_server, cmdb_ci_appl


# ---------------------------------------------------------------------------- agent outputs


@dataclass
class Evidence:
    """Everything the specialist agents found for one incident."""
    kb_candidates: list[dict[str, Any]] = field(default_factory=list)
    similar_incidents: list[dict[str, Any]] = field(default_factory=list)
    problem_candidates: list[dict[str, Any]] = field(default_factory=list)
    change_candidates: list[dict[str, Any]] = field(default_factory=list)
    diagnostics: dict[str, Any] = field(default_factory=dict)
    ci: Optional[dict[str, Any]] = None


@dataclass
class TriageDecision:
    """What the reasoner (heuristic or Claude) decided from the evidence."""
    assignment_group: str
    priority: int
    is_noise: bool
    kb_article: Optional[str]
    root_cause: str
    related_change: Optional[str] = None
    related_problem: Optional[str] = None
    confidence: float = 0.0
    rationale: str = ""
    reasoner: str = "heuristic"


@dataclass
class RemediationPlan:
    runbook: Optional[str]
    mode: str                  # "automated" | "manual" | "none"
    safe_to_automate: bool
    parameters: dict[str, Any] = field(default_factory=dict)
    reason: str = ""
    approval: Optional[dict[str, Any]] = None
    executed: bool = False
    job: Optional[dict[str, Any]] = None


@dataclass
class TriageResult:
    incident_key: str
    incident_number: Optional[str]
    short_description: str
    decision: TriageDecision
    remediation: RemediationPlan
    evidence: Evidence
    work_note: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)
